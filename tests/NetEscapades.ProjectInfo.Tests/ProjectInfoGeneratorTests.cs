using System.Collections.Generic;
using FluentAssertions;
using Xunit;
using static NetEscapades.ProjectInfo.Tests.ProjectInfoItems;

namespace NetEscapades.ProjectInfo.Tests;

public class ProjectInfoGeneratorTests
{
    private const string Source = "public class MyClass { }";

    private static string Normalize(string value) => value.Replace("\r\n", "\n");

    private static string GenerateValid(Dictionary<string, string> config)
    {
        var (diagnostics, output) = TestHelpers.GetGeneratedOutput(
            [new ProjectInfoGenerator()], new TestHelpers.Options(config, Source));

        diagnostics.Should().BeEmpty();
        return Normalize(output);
    }

    private static string GenerateValid(params string[] items) => GenerateValid(Config(items));

    [Fact]
    public void NoItems_EmitsNothing()
        => GenerateValid().Should().BeEmpty();

    [Fact]
    public void EmptyItemsProperty_EmitsNothing()
        => GenerateValid(new Dictionary<string, string> { [ItemsKey] = "" }).Should().BeEmpty();

    [Fact]
    public void GeneratesStringConstants()
    {
        var output = GenerateValid(S("Version", "1.2.3"), S("Name", "My App"));

        output.Should().Be(Normalize($$"""
            // <auto-generated/>
            #nullable enable

            [global::System.CodeDom.Compiler.GeneratedCode("NetEscapades.ProjectInfo", "{{Constants.Version}}")]
            internal static partial class ProjectInfo
            {
                public const string Version = "1.2.3";
                public const string Name = "My App";
            }

            """));
    }

    [Fact]
    public void GeneratesUtf8Properties()
    {
        var output = GenerateValid(U("VersionBytes", "4.5.6"));

        output.Should().Be(Normalize($$"""
            // <auto-generated/>
            #nullable enable

            [global::System.CodeDom.Compiler.GeneratedCode("NetEscapades.ProjectInfo", "{{Constants.Version}}")]
            internal static partial class ProjectInfo
            {
                public static global::System.ReadOnlySpan<byte> VersionBytes => "4.5.6"u8;
            }

            """));
    }

    [Fact]
    public void GeneratesStringsAndUtf8_InOrder()
    {
        var output = GenerateValid(S("Version", "1.2.3"), U("VersionBytes", "4.5.6"));

        output.Should().Contain("""public const string Version = "1.2.3";""")
            .And.Contain("""public static global::System.ReadOnlySpan<byte> VersionBytes => "4.5.6"u8;""");
        output.IndexOf("Version =").Should().BeLessThan(output.IndexOf("VersionBytes"));
    }

    [Fact]
    public void UsesRootNamespaceWhenSet()
    {
        var output = GenerateValid(Config(
            [S("Version", "1.2.3")],
            ("build_property.RootNamespace", "My.Company")));

        output.Should().Be(Normalize($$"""
            // <auto-generated/>
            #nullable enable

            namespace My.Company
            {
                [global::System.CodeDom.Compiler.GeneratedCode("NetEscapades.ProjectInfo", "{{Constants.Version}}")]
                internal static partial class ProjectInfo
                {
                    public const string Version = "1.2.3";
                }
            }

            """));
    }

    [Theory]
    [InlineData("")]
    [InlineData("  ")]
    [InlineData("1Invalid")]
    [InlineData("My..Company")]
    [InlineData("class")]
    public void UsesGlobalNamespaceWhenRootNamespaceIsMissingOrInvalid(string rootNamespace)
    {
        var output = GenerateValid(Config(
            [S("Version", "1.2.3")],
            ("build_property.RootNamespace", rootNamespace)));

        output.Should().NotContain("namespace");
    }

    [Theory]
    [InlineData("public", "public static partial class ProjectInfo")]
    [InlineData("PUBLIC", "public static partial class ProjectInfo")]
    [InlineData("internal", "internal static partial class ProjectInfo")]
    [InlineData("nonsense", "internal static partial class ProjectInfo")]
    public void RespectsVisibility(string visibility, string expected)
    {
        var output = GenerateValid(Config(
            [S("Version", "1.2.3")],
            ("build_property.ProjectInfoVisibility", visibility)));

        output.Should().Contain(expected);
    }

    [Fact]
    public void EscapesValues()
    {
        // Values can contain separators, quotes, comment characters, backslashes, newlines and non-ASCII characters
        var output = GenerateValid(
            S("Odd", "a \"b\" | c , d ; e # f \\ g\nsecond line é 😀"),
            U("OddBytes", "x\"y"));

        output.Should()
            .Contain("""public const string Odd = "a \"b\" | c , d ; e # f \\ g\nsecond line é 😀";""")
            .And.Contain("""=> "x\"y"u8;""");
    }

    [Fact]
    public void ChangingConfigRegeneratesOutput()
    {
        GenerateValid(S("Version", "1.2.3")).Should().Contain("internal static");
        GenerateValid(Config([S("Version", "1.2.3")], ("build_property.ProjectInfoVisibility", "public")))
            .Should().Contain("public static");
    }
}
