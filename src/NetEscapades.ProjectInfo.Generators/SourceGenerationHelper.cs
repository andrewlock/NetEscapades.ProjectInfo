using System.Globalization;
using System.Text;

namespace NetEscapades.ProjectInfo;

internal static class SourceGenerationHelper
{
    /// <summary>The approximate size of everything that is emitted other than the names and values</summary>
    public const int HeaderCapacity = 256;

    /// <summary>The approximate size of the "public ... Name = ...;" boilerplate for a single entry</summary>
    public const int EntryCapacity = 100;

    /// <summary>The entry is validated and should be emitted</summary>
    public const byte Emit = 0;

    /// <summary>
    /// Generates the ProjectInfo class containing all of the <paramref name="entries"/> whose
    /// corresponding <paramref name="states"/> are <see cref="Emit"/>.
    /// </summary>
    /// <param name="capacity">The expected length of the output, to avoid growing the builder</param>
    public static string Generate(
        ProjectInfoConfig config,
        ReadOnlySpan<ProjectInfoEntry> entries,
        ReadOnlySpan<byte> states,
        int capacity)
    {
        var sb = new StringBuilder(capacity);
        sb.Append("// <auto-generated/>\n#nullable enable\n\n");

        var indent = "";
        if (config.RootNamespace is { } ns)
        {
            sb.Append("namespace ").Append(ns).Append("\n{\n");
            indent = "    ";
        }

        sb.Append(indent).Append("[global::System.CodeDom.Compiler.GeneratedCode(\"NetEscapades.ProjectInfo\", \"")
            .Append(Constants.Version).Append("\")]\n");
        sb.Append(indent).Append(config.IsPublic ? "public" : "internal")
            .Append(" static partial class ").Append(Constants.ClassName).Append('\n');
        sb.Append(indent).Append("{\n");

        for (var i = 0; i < entries.Length; i++)
        {
            if (states[i] != Emit)
            {
                continue;
            }

            ref readonly var entry = ref entries[i];
            sb.Append(indent).Append("    public ");
            if (entry.Kind == ProjectInfoKind.String)
            {
                sb.Append("const string ").Append(entry.Name).Append(" = ");
                AppendLiteral(sb, entry.Value!);
                sb.Append(";\n");
            }
            else
            {
                sb.Append("static global::System.ReadOnlySpan<byte> ").Append(entry.Name).Append(" => ");
                AppendLiteral(sb, entry.Value!);
                sb.Append("u8;\n");
            }
        }

        sb.Append(indent).Append("}\n");
        if (config.RootNamespace is not null)
        {
            sb.Append("}\n");
        }

        return sb.ToString();
    }

    /// <summary>
    /// Appends <paramref name="value"/> as a quoted C# string literal, appending runs of characters that
    /// don't need escaping in one go and without allocating intermediate strings.
    /// </summary>
    private static void AppendLiteral(StringBuilder sb, string value)
    {
        sb.Append('"');

        var runStart = 0;
        for (var i = 0; i < value.Length; i++)
        {
            var c = value[i];
            string? escape;
            if (c == '"')
            {
                escape = "\\\"";
            }
            else if (c == '\\')
            {
                escape = "\\\\";
            }
            else if (c >= ' ' && c < 0x7F)
            {
                continue;
            }
            else if (c < 0x80 || NeedsUnicodeEscape(c))
            {
                escape = GetSimpleEscape(c);
            }
            else
            {
                continue;
            }

            sb.Append(value, runStart, i - runStart);
            runStart = i + 1;
            if (escape is not null)
            {
                sb.Append(escape);
            }
            else
            {
                AppendUnicodeEscape(sb, c);
            }
        }

        sb.Append(value, runStart, value.Length - runStart);
        sb.Append('"');
    }

    private static string? GetSimpleEscape(char c) => c switch
    {
        '\0' => "\\0",
        '\a' => "\\a",
        '\b' => "\\b",
        '\f' => "\\f",
        '\n' => "\\n",
        '\r' => "\\r",
        '\t' => "\\t",
        '\v' => "\\v",
        _ => null,
    };

    private static void AppendUnicodeEscape(StringBuilder sb, char c)
    {
        const string hex = "0123456789abcdef";
        sb.Append("\\u")
            .Append(hex[(c >> 12) & 0xF])
            .Append(hex[(c >> 8) & 0xF])
            .Append(hex[(c >> 4) & 0xF])
            .Append(hex[c & 0xF]);
    }

    /// <summary>
    /// Whether the character can't be written as-is: control, format, private-use, unassigned and separator
    /// characters. Surrogates are always valid pairs, as the value is decoded from escaped UTF-8.
    /// </summary>
    private static bool NeedsUnicodeEscape(char c)
    {
        switch (CharUnicodeInfo.GetUnicodeCategory(c))
        {
            case UnicodeCategory.Control:
            case UnicodeCategory.Format:
            case UnicodeCategory.PrivateUse:
            case UnicodeCategory.OtherNotAssigned:
            case UnicodeCategory.LineSeparator:
            case UnicodeCategory.ParagraphSeparator:
                return true;
            default:
                return false;
        }
    }
}
