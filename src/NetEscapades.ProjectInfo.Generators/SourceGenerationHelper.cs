using System.Text;
using Microsoft.CodeAnalysis.CSharp;

namespace NetEscapades.ProjectInfo;

internal static class SourceGenerationHelper
{
    public static string Generate(ProjectInfoConfig config, List<ProjectInfoEntry> entries)
    {
        var sb = new StringBuilder();
        sb.Append("// <auto-generated/>\n#nullable enable\n\n");

        var indent = "";
        if (config.RootNamespace is { } ns)
        {
            sb.Append("namespace ").Append(ns).Append("\n{\n");
            indent = "    ";
        }

        sb.Append(indent).Append("[global::System.CodeDom.Compiler.GeneratedCode(\"NetEscapades.ProjectInfo\", \"")
            .Append(Constants.Version).Append("\")]\n");
        sb.Append(indent).Append(config.IsPublic ? "public" : "internal")
            .Append(" static partial class ").Append(Constants.ClassName).Append('\n');
        sb.Append(indent).Append("{\n");

        foreach (var entry in entries)
        {
            var literal = SymbolDisplay.FormatLiteral(entry.Value!, quote: true);
            sb.Append(indent).Append("    public ");
            if (entry.Kind == ProjectInfoKind.String)
            {
                sb.Append("const string ").Append(entry.Name).Append(" = ").Append(literal).Append(";\n");
            }
            else
            {
                sb.Append("static global::System.ReadOnlySpan<byte> ").Append(entry.Name)
                    .Append(" => ").Append(literal).Append("u8;\n");
            }
        }

        sb.Append(indent).Append("}\n");
        if (config.RootNamespace is not null)
        {
            sb.Append("}\n");
        }

        return sb.ToString();
    }
}
